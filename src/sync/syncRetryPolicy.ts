// Повтор завели ради одного конкретного случая: сразу после входа
// (pairWithCode) Supabase иногда отвечает 401 на первый же запрос данных —
// токен уже выдан, но ещё не везде распространился; через секунду-другую
// тот же запрос проходит сам. Слияние идемпотентно (см. syncEngine.ts),
// поэтому повторить весь прогон в этом случае безопасно.
//
// Но написан повтор был «на любой сбой». А полный прогон синка поднимает в
// память все записи стора разом (фото — base64-строками) — тяжелее уже
// некуда. Повторить его тут же ещё раз при сбое по ДРУГОЙ причине —
// например, при нехватке памяти — значит НАВЕРНЯКА удвоить пиковое
// потребление в момент, когда памяти и так не хватило. Поэтому повторяем
// только то, ради чего повтор и заводили: похожее на ошибку авторизации.
//
// Чистая функция: разбирает то, что уже поймано в catch, ничего не ждёт и
// никуда не стучится — чтобы проверялась тестом на выдуманных объектах
// ошибок, а не на живом сбое Supabase.
// ============================================================

export function isAuthLikeSyncError(error: unknown): boolean {
  const status = error && typeof error === 'object' ? (error as { status?: unknown }).status : undefined;
  if (status === 401 || status === 403) return true;

  const message = error instanceof Error ? error.message : typeof error === 'string' ? error : '';
  if (!message) return false;
  if (/\b(401|403)\b/.test(message)) return true;
  return /jwt|unauthorized|not authenticated/i.test(message);
}
