// ТЕКСТЫ О СБОЯХ ХРАНИЛИЩА
//
// Было двадцать формулировок про одно и то же: «Хранилище недоступно —
// изменения не сохранены», «Не удалось сохранить изменения», «Не удалось
// сохранить черновик контента», «Хранилище недоступно — проект не удалён»…
// Мастер видела то одно, то другое и не понимала, одна это поломка или
// разные, и что делать.
//
// Смыслов на самом деле четыре, и различать их важно, потому что действия
// РАЗНЫЕ:
//
//   lost        — связи с хранилищем нет. Нужно переподключиться («Повторить»).
//   write       — связь есть, запись не удалась. Действие мастера НЕ сохранено,
//                 нужно повторить его самой.
//   read        — связь есть, чтение не удалось. Данные целы, поможет
//                 обновление страницы.
//   conflicting — дневник открыт в другой вкладке и обновляет хранилище.
//
// Текст собирается из состояния и названия операции («сохранение клиента»),
// поэтому новых формулировок больше не появляется — появляются только новые
// названия операций.
// ============================================================

export type StorageFailureKind = 'lost' | 'write' | 'read' | 'conflicting';

// Что именно делал дневник. Отдельный список, чтобы названия операций были
// одинаковыми и в сообщении, и в журнале сбоев (см. lib/errorLog.ts).
export const STORAGE_ACTIONS = {
  loadClients: 'загрузка клиентов',
  loadProjects: 'загрузка проектов',
  loadContent: 'загрузка черновиков контента',
  loadJobs: 'загрузка фоновых задач',
  loadMasterInfo: 'загрузка личного кабинета',
  saveClient: 'сохранение клиента',
  saveProject: 'сохранение проекта',
  saveContent: 'сохранение черновика контента',
  saveMasterInfo: 'сохранение личного кабинета',
  deleteClient: 'удаление клиента',
  deleteProject: 'удаление проекта',
  deleteContent: 'удаление записи контента',
  deleteJob: 'удаление фоновой задачи',
  migrateRecords: 'перенос записей в проекты',
  migrateMasterInfo: 'перенос личного кабинета',
  importData: 'импорт данных',
  readBackup: 'чтение данных для копии',
  measureStorage: 'подсчёт занятого места',
  clearLegacyRecords: 'очистка старых копий',
  open: 'подключение к хранилищу',
} as const;

export type StorageAction = (typeof STORAGE_ACTIONS)[keyof typeof STORAGE_ACTIONS];

// Одно предложение о сути и одно о том, что делать. Без технических слов:
// «транзакция», «IndexedDB» и «соединение» мастеру ничего не говорят.
const KIND_TEXT: Record<StorageFailureKind, { what: string; todo: string }> = {
  lost: {
    what: 'Хранилище отключилось',
    todo: 'Нажмите «Повторить» — данные на месте.',
  },
  write: {
    what: 'Не удалось сохранить',
    todo: 'Повторите последнее действие.',
  },
  read: {
    what: 'Не удалось прочитать данные',
    todo: 'Обновите страницу — сами данные целы.',
  },
  conflicting: {
    what: 'Дневник открыт ещё в одной вкладке',
    todo: 'Закройте лишнюю вкладку и нажмите «Повторить».',
  },
};

// Сообщение для плашки. action указывается, когда мастер могла не понять,
// что именно не сохранилось; для «отключилось» она не нужна — там речь про
// хранилище целиком, а не про конкретную операцию.
export function storageFailureMessage(kind: StorageFailureKind, action?: string): string {
  const { what, todo } = KIND_TEXT[kind];
  if (kind === 'lost' || kind === 'conflicting' || !action) return `${what}. ${todo}`;
  return `${what}: ${action}. ${todo}`;
}

// Нужна ли кнопка «Повторить» — она чинит только потерю связи. При отказе
// записи переподключаться не к чему: связь есть, повторить нужно само
// действие.
export function storageFailureNeedsReconnect(kind: StorageFailureKind): boolean {
  return kind === 'lost' || kind === 'conflicting';
}
