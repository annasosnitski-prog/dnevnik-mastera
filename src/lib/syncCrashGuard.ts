// ЗАЩИТА ОТ ПЕТЛИ ПАДЕНИЙ СИНКА
//
// Реальный сюжет с планшета: полный прогон синка (см. syncEngine.ts)
// поднимает в память все фото стора разом, память кончается, WebKit убивает
// процесс страницы — не долетев ни до какого catch. useSyncDriver.ts при
// этом сам стартует синк на каждом запуске приложения и при каждом
// возврате из фона, поэтому получалась петля: упали → Safari перезапустил
// страницу → синк стартовал снова → снова упали. И ни одного следа в
// журнале сбоев: обычный try/catch тут бессилен, процесс не падает С
// ошибкой, он просто исчезает.
//
// Метод тот же, что и для петли перезагрузок при обновлении версии (см.
// appUpdate.ts): перед прогоном кладём в localStorage отметку «начали»,
// снимаем её по завершении. Если при следующем запуске отметка на месте —
// значит, прошлый прогон не долетел до своего же finally, и это ровно то
// доказательство падения по памяти, которого не хватало.
//
// Решение здесь чистое (никакого localStorage/Date.now изнутри) — чтобы
// его можно было проверить тестом, а не воспроизводить petлю на живом
// планшете.
// ============================================================

// Ключ отметки. Экспортирован, чтобы исполняющий код (useSyncDriver.ts)
// читал/писал/удалял ровно то же значение, которое здесь разбирается.
export const SYNC_STARTED_AT_KEY = 'inka-sync-started-at';

export type SyncStartupDecision =
  // Отметки нет или она не похожа на дату — прошлый прогон (если был)
  // завершился штатно.
  | { kind: 'clean' }
  // Отметка осталась висеть — прошлый прогон был прерван, не снял её сам.
  | { kind: 'crashed'; startedAt: string };

export function decideSyncStartup(rawStartedAt: string | null): SyncStartupDecision {
  if (!rawStartedAt) return { kind: 'clean' };
  // Мусор в localStorage (ручное редактирование, старый формат) — не резон
  // считать это падением и блокировать автосинк навсегда.
  if (Number.isNaN(Date.parse(rawStartedAt))) return { kind: 'clean' };
  return { kind: 'crashed', startedAt: rawStartedAt };
}

// Текст в lastError для экрана настроек. Кнопка «Синхронизировать сейчас»
// остаётся рабочей — заблокирован только автозапуск, поэтому текст прямо
// об этом говорит, а не пугает поломкой, которую нечем чинить самой мастеру.
export function syncCrashExplanation(startedAt: string): string {
  const when = new Date(startedAt);
  const stamp = Number.isNaN(when.getTime()) ? startedAt : when.toLocaleString('ru-RU');
  return (
    `Прошлая синхронизация (начата ${stamp}) не завершилась — похоже, приложение ` +
    `закрылось или упало прямо во время неё. Автозапуск синка приостановлен до ` +
    `следующей ручной попытки: нажмите «Синхронизировать сейчас».`
  );
}

// Текст для журнала сбоев (lib/errorLog.ts, источник 'sync'). Отдельно от
// syncCrashExplanation: в lastError мастер должна прочитать, что делать
// дальше, а в журнале — техническую заметку с точным временем для разбора.
export function syncCrashLogMessage(startedAt: string): string {
  return `Предыдущий прогон синхронизации начался ${startedAt} и не снял отметку о начале — вкладка, скорее всего, упала во время синка.`;
}
