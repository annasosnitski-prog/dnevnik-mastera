// ИМПОРТ КОПИИ: ЧТО ИМЕННО ВЫБРАЛИ И ЧТО БЫЛО ПОСЛЕ
//
// Два маленьких куска логики импорта, которым нечего делать внутри экрана:
// объяснение отказа (почему выбранный файл не копия) и передача результата
// восстановления через перезагрузку страницы.
// ============================================================

// Заголовок, который раньше уходил в окно «Поделиться» рядом с файлом
// (см. shareOrDownloadFile). Сам он туда больше не передаётся, но у мастера
// на телефоне уже лежат файлы, созданные ИЗ НЕГО, а не из архива, — и когда
// такой файл приносят на импорт, честный ответ «это не копия» бесполезен:
// человек уверен, что копию делал. Поэтому текст остаётся здесь — чтобы его
// узнавать.
export const LEGACY_BACKUP_SHARE_TITLE = 'INKA — резервная копия';

// Больше в «подсунули не тот файл» не бывает: настоящий архив — это десятки
// килобайт минимум (один манифест с оглавлением уже больше).
const TEXT_ARTEFACT_MAX_BYTES = 4096;

/**
 * Почему выбранный файл не удалось прочитать как копию. Формулировка на
 * экране должна вести к следующему действию, а не к «попробуйте другой файл»:
 * самый частый случай — телефон сохранил не архив, а текст из окна
 * «Поделиться», и повторять тот же путь бессмысленно.
 */
export function describeUnreadableBackupFile(file: { name: string; size: number }, head: string): string {
  if (file.size === 0) {
    return 'Файл пустой — в нём нет ни одной записи. Сделайте копию заново: «Подготовить копию», затем «Сохранить / поделиться».';
  }
  const text = head.trim();
  if (file.size <= TEXT_ARTEFACT_MAX_BYTES && text.startsWith(LEGACY_BACKUP_SHARE_TITLE)) {
    return `Здесь только название копии (${file.size} б), а не сама копия: телефон сохранил текст из окна «Поделиться» вместо файла. Сделайте копию заново и в окне «Поделиться» выберите «Сохранить в Файлы» — рядом с именем должен быть файл inka-backup-….zip.`;
  }
  if (file.size <= TEXT_ARTEFACT_MAX_BYTES && !text.startsWith('{') && !text.startsWith('[')) {
    return `Это обычный текст (${file.size} б), а не резервная копия. Копия — это файл inka-backup-….zip из окна «Поделиться».`;
  }
  return 'Не удалось прочитать файл — проверьте, что это резервная копия INKA.';
}

// ── Итог восстановления через перезагрузку ────────────────────────────────
// После успешного восстановления дневник перезапускается (см. confirmImport):
// иначе только что восстановленная библиотека читается из базы В ТУ ЖЕ
// страницу, которая минуту назад разбирала архив, — и на телефоне это тот
// самый белый экран. Перезагрузка стирает и сообщение об успехе, поэтому оно
// переживает её здесь.
export const IMPORT_RESULT_KEY = 'inka-import-result';

export function rememberImportResult(text: string): void {
  try {
    localStorage.setItem(IMPORT_RESULT_KEY, text);
  } catch {
    // Не смогли запомнить — потеряется только поздравление, не данные.
  }
}

export function takeImportResult(): string | null {
  try {
    const text = localStorage.getItem(IMPORT_RESULT_KEY);
    if (text) localStorage.removeItem(IMPORT_RESULT_KEY);
    return text || null;
  } catch {
    return null;
  }
}
