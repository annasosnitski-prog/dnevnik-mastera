// ============================================================
// САМОВОССТАНОВЛЕНИЕ ХРАНИЛИЩА
//
// Соединение с IndexedDB рвётся не потому, что что-то сломалось, а потому
// что так устроены телефоны. iOS усыпляет приложение на домашнем экране и
// закрывает соединение; браузер закрывает его под нехваткой памяти (а память
// кончается ровно там, где мастер работает с фото). Это НОРМА, а не авария.
//
// Раньше дневник реагировал на это как на аварию: красная плашка «Хранилище
// отключилось» и кнопка «Повторить», которую мастер обязана нажать руками.
// Каждое возвращение в приложение — плашка. Отсюда и ощущение «мигает и
// разваливается»: чинить руками то, что дневник умеет починить сам.
//
// Здесь — решения этого восстановления, отдельно от React:
//
//  1. Сколько ждать перед очередной попыткой переподключиться (пауза растёт,
//     чтобы серия неудач не жгла батарею).
//  2. Показывать ли мастеру плашку — или молча чинить дальше. Плашка только
//     тогда, когда все тихие попытки исчерпаны и без человека уже никак.
//  3. Очередь отложенных записей: действие, которое не удалось записать из-за
//     оборвавшегося соединения, не выбрасывается, а ждёт восстановления и
//     повторяется. Раньше оно просто пропадало вместе с тем, что мастер
//     только что ввела.
// ============================================================

// Паузы между тихими попытками. Первая почти мгновенная: типичный случай —
// соединение закрылось, пока приложение спало, и открывается оно сразу.
// Дальше пауза растёт: если не вышло трижды, дело не в «моргнуло».
export const RECONNECT_DELAYS_MS = [150, 700, 2500] as const;

// Сколько тихих попыток делаем, прежде чем побеспокоить мастера.
export const RECONNECT_SILENT_ATTEMPTS = RECONNECT_DELAYS_MS.length;

// Сколько соединение должно прожить, чтобы считаться состоявшимся.
//
// Счётчик попыток обнуляется при удачном подключении — иначе одна давняя
// серия неудач навсегда осталась бы «уже исчерпанной». Но если соединение
// открывается и тут же закрывается (браузеру не хватает памяти — открыть он
// её ещё может, удержать уже нет), обнуление на каждом таком цикле означало
// бы вечный круг «открылись — упали — открылись», молча и на батарее.
// Поэтому серия продолжается, пока соединение не прожило осмысленное время.
export const STABLE_CONNECTION_MS = 10_000;

export function isConnectionStable(connectedAt: number | null, now: number): boolean {
  if (connectedAt === null) return false;
  return now - connectedAt >= STABLE_CONNECTION_MS;
}

// Пауза перед попыткой номер attempt (нумерация с 1). null — тихие попытки
// кончились, дальше только с ведома мастера.
export function reconnectDelayMs(attempt: number): number | null {
  if (attempt < 1) return RECONNECT_DELAYS_MS[0];
  return RECONNECT_DELAYS_MS[attempt - 1] ?? null;
}

// Состояние связи с хранилищем — именно то, что видит мастер.
//
//   connecting — первое открытие при запуске: рисуем дневник, молчим.
//   ready      — всё хорошо.
//   recovering — связь пропала, чиним сами. МОЛЧА: плашки нет.
//   failed     — сами не справились, нужна мастер.
export type StoragePhase = 'connecting' | 'ready' | 'recovering' | 'failed';

// Единственное правило показа красной плашки о потере связи. Вынесено сюда,
// потому что весь смысл переделки в нём: пока чиним сами — не пугаем.
export function shouldShowLostBanner(phase: StoragePhase): boolean {
  return phase === 'failed';
}

// ── Очередь отложенных записей ───────────────────────────────────────────
//
// Ключ — что именно записывается («client:42», «projects», «master-info»).
// Повторная запись того же ключа ЗАМЕНЯЕТ прежнюю, не добавляется: в очереди
// должно лежать последнее состояние записи, а не история правок. Позиция при
// этом сохраняется — порядок между разными сущностями важен (проект должен
// лечь раньше, чем ссылающийся на него контент).
export interface PendingWrite {
  key: string;
  // Название операции человеческими словами — для сообщения и журнала,
  // если восстановиться так и не удастся (см. STORAGE_ACTIONS).
  action: string;
  // Соединение приходит параметром, а не из замыкания: замыкание создавалось
  // ровно в тот момент, когда соединения не было, и своё «db» помнит пустым.
  run: (database: IDBDatabase) => void;
}

// Очередь не бесконечная: если связь не вернулась, а мастер продолжает
// работать, дневник не имеет права раздуть память до падения. Двадцати
// отложенных записей хватает на любую разумную серию правок подряд.
export const PENDING_WRITE_LIMIT = 20;

export function enqueuePendingWrite(
  queue: readonly PendingWrite[],
  write: PendingWrite,
  limit: number = PENDING_WRITE_LIMIT,
): PendingWrite[] {
  const existing = queue.findIndex((item) => item.key === write.key);
  if (existing !== -1) {
    const next = queue.slice();
    next[existing] = write;
    return next;
  }
  // Переполнение: выбрасываем САМУЮ СТАРУЮ. Свежая правка ценнее — она та,
  // которую мастер только что сделала и помнит.
  const next = [...queue, write];
  return next.length > limit ? next.slice(next.length - limit) : next;
}

// Что сказать мастеру, если отложенные записи так и не удалось положить.
// Перечислять все операции незачем — важно их число и то, что они не потеряны
// молча.
export function pendingWriteSummary(queue: readonly PendingWrite[]): string | null {
  if (queue.length === 0) return null;
  if (queue.length === 1) return `Не сохранено: ${queue[0].action}.`;
  return `Не сохранено изменений: ${queue.length}.`;
}
