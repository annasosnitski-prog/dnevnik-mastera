// ============================================================
// ЧЕРНОВИКИ РЕЗЕРВНЫХ КОПИЙ (OPFS)
//
// Копия собирается не в памяти, а файлом в OPFS — приватной файловой системе
// сайта, — и только потом уезжает через окно «Поделиться». Это правильно:
// иначе многосотмегабайтный архив пришлось бы держать в памяти страницы.
//
// Но у этого каталога не было хозяина, и он превратился в свалку. Как это
// выглядело у мастера: занято 71 ГБ при 473 МБ реальных данных.
//
// Почему копилось:
//
//  1. Имя архива содержит ДАТУ, а не номер попытки
//     (inka-backup-<имя>-2026-09-03.zip). Сборка удаляла перед началом ровно
//     это имя — то есть только сегодняшний файл. Архив, оставшийся со
//     вчера, не удалял никто и никогда.
//
//  2. Уборка при сбое жила в catch. А главный сценарий обрыва здесь — не
//     исключение, а УБИТАЯ ВКЛАДКА: сборка копии это самый тяжёлый момент
//     в жизни дневника, браузер снимает страницу под нехваткой памяти, и
//     тогда не выполняется вообще никакой JS. Ни catch, ни finally.
//
//  3. Запись через createWritable() держит служебный файл подкачки рядом с
//     целевым. Убитая вкладка оставляет и его, а removeEntry по имени
//     архива до него не дотягивается.
//
// И это не просто занятое место. Требование свободного места для новой копии
// считалось от общего usage хранилища (см. checkFreeSpace) — в расчёте на то,
// что источник в этом хранилище один, сам дневник. Свалка это предположение
// ломает: мусор раздувал usage, usage раздувал требование, и дневник отказывал
// в сборке копии, требуя 56 ГБ свободного места. Мусор при этом не убирался,
// потому что убирала его только сборка копии. Замкнутый круг, в котором
// мастер не может сделать копию ВООБЩЕ — при невосстановимых данных и
// последней копии двухнедельной давности.
//
// Поэтому уборка живёт здесь, отдельным модулем без zip.js: её нужно
// запускать при старте дневника, а тянуть в основной бандл 139 кБ архиватора
// ради этого нельзя.
// ============================================================

export const BACKUP_SCRATCH_DIRECTORY = 'inka-prepared-backups';

export interface SweepResult {
  removed: number;
  bytes: number;
}

function opfsRoot(): (() => Promise<FileSystemDirectoryHandle>) | undefined {
  const storage = navigator.storage as
    | (StorageManager & { getDirectory?: () => Promise<FileSystemDirectoryHandle> })
    | undefined;
  if (!storage?.getDirectory) return undefined;
  return () => storage.getDirectory!.call(storage);
}

// Всё, что лежит в этом каталоге, — черновик прошлой сборки. Готовая копия
// здесь не живёт: она уезжает через «Поделиться» и удаляется вызывающей
// стороной. Значит выметать можно всё подряд, а не подбирать имена: именно
// подбор имён и оставлял мусор от прошлых дней и файлы подкачки.
//
// Когда это безопасно: при старте дневника (никакая копия не может быть «в
// пути» — страница только что загрузилась) и перед началом новой сборки
// (новый файл ещё не создан). В обоих случаях в каталоге нет ничего живого.
export async function sweepBackupScratch(): Promise<SweepResult> {
  const getDirectory = opfsRoot();
  if (!getDirectory) return { removed: 0, bytes: 0 };
  let directory: FileSystemDirectoryHandle;
  try {
    const root = await getDirectory();
    // create: false — на свежей установке каталога нет, и создавать его
    // только чтобы тут же подмести, незачем.
    directory = await root.getDirectoryHandle(BACKUP_SCRATCH_DIRECTORY, { create: false });
  } catch {
    return { removed: 0, bytes: 0 };
  }

  // Сначала собираем имена, потом удаляем: удалять во время обхода итератора
  // каталога — не то, на что можно рассчитывать.
  const names: string[] = [];
  let bytes = 0;
  try {
    const iterable = directory as FileSystemDirectoryHandle & {
      values?: () => AsyncIterableIterator<FileSystemHandle>;
    };
    if (!iterable.values) return { removed: 0, bytes: 0 };
    for await (const handle of iterable.values()) {
      names.push(handle.name);
      // Размер только для отчёта — не смогли узнать, значит не покажем.
      if (handle.kind === 'file') {
        try {
          bytes += (await (handle as FileSystemFileHandle).getFile()).size;
        } catch {
          /* размер необязателен */
        }
      }
    }
  } catch {
    return { removed: 0, bytes: 0 };
  }

  let removed = 0;
  for (const name of names) {
    try {
      // recursive — на случай, если реализация держит подкачку подкаталогом.
      await directory.removeEntry(name, { recursive: true });
      removed += 1;
    } catch {
      // Занятый системой файл пропускаем: подметём при следующем запуске.
    }
  }
  return { removed, bytes };
}
